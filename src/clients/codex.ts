// Codex integration modelled on `ollama launch codex`: a dedicated profile
// (<CODEX_HOME>/opencode-bridge.config.toml) and model catalog for the CLI, and a
// journaled, reversible root config.toml selection for the Codex app.
const exec = promisify(execFile);
export const CODEX_PROFILE = 'opencode-bridge';
const PROVIDER = 'opencode-bridge';
const BEGIN = '# >>> OpenCode Bridge (managed, restored on disconnect) >>>';
const END = '# <<< OpenCode Bridge <<<';
const ROOT_KEYS = ['model', 'model_provider', 'model_catalog_json', 'model_reasoning_effort'];
const REASONING: Record<string, string> = { low: 'Fast responses with lighter reasoning', medium: 'Balances speed and reasoning depth', high: 'Greater reasoning depth for complex problems', xhigh: 'Extra high reasoning depth', max: 'Maximum reasoning depth' };

export const codexHome = () => process.env.CODEX_HOME || join(homedir(), '.codex');
const toml = (value: string) => JSON.stringify(value);
async function writePrivate(path: string, text: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const temp = `${path}.${randomUUID()}.tmp`;
  try {
    const handle = await open(temp, 'wx', 0o600);
    try { await handle.writeFile(text); await handle.sync(); } finally { await handle.close(); }
    await rename(temp, path);
  } finally { await unlink(temp).catch(() => {}); }
}
async function readText(path: string): Promise<string | undefined> {
  try { return await readFile(path, 'utf8'); } catch (err: any) { if (err.code === 'ENOENT') return undefined; throw err; }
}
export function catalog(routes: Route[], names: Record<string, string> = {}): Wire {
  return { models: routes.map(route => ({
    slug: route.id, display_name: route.displayName || names[route.ref] || route.label.split(' · ')[0] || route.ref, description: route.displayName ? `Answered by ${route.label.split(' · ')[0]} via OpenCode Bridge` : `${route.label} via OpenCode Bridge`,
    context_window: route.contextTokens, max_context_window: route.contextTokens, effective_context_window_percent: 95,
    shell_type: 'default', visibility: 'list', supported_in_api: true, priority: 0,
    truncation_policy: { mode: 'tokens', limit: 10000 }, input_modalities: route.vision ? ['text', 'image'] : ['text'],
    base_instructions: '', support_verbosity: false, default_verbosity: null,
    supports_parallel_tool_calls: route.protocol !== 'opencode', supports_reasoning_summaries: false, default_reasoning_summary: 'auto',
    supported_reasoning_levels: (route.effort?.levels || []).map(effort => ({ effort, description: REASONING[effort] })),
    default_reasoning_level: route.effortOverride || null,
    experimental_supported_tools: [], apply_patch_tool_type: null, additional_speed_tiers: [], supports_search_tool: false,
  })) };
}
export function providerTable(config: BridgeConfig): string {
  return [`[model_providers.${PROVIDER}]`, `name = ${toml('OpenCode Bridge')}`, `base_url = ${toml(`http://127.0.0.1:${config.port}/v1`)}`, 'wire_api = "responses"',
    // A loopback-only gateway credential; Codex sends it as a bearer token.
    `experimental_bearer_token = ${toml(config.token)}`, 'requires_openai_auth = false', 'stream_idle_timeout_ms = 1800000'].join('\n');
}
function selection(route: Route, catalogPath: string): string[] {
  return [`model = ${toml(route.id)}`, `model_provider = ${toml(PROVIDER)}`, `model_catalog_json = ${toml(catalogPath)}`, ...(route.effortOverride ? [`model_reasoning_effort = ${toml(route.effortOverride)}`] : [])];
}
export function profileText(config: BridgeConfig, route: Route, catalogPath: string): string {
  return `# Generated by OpenCode Bridge. Use: codex --profile ${CODEX_PROFILE}\n${selection(route, catalogPath).join('\n')}\n\n${providerTable(config)}\n`;
}
// Text-level edit keeps the user's comments and ordering. Only top-level
// selection keys move into the managed block; the journal restores them verbatim.
export function applyRoot(original: string, block: string[], table: string): { text: string; removed: string[] } {
  if (original.includes(BEGIN)) throw new Error('Codex already has an OpenCode Bridge block. Disconnect Codex first.');
  if (new RegExp(`^\\s*\\[model_providers\\.(?:"${PROVIDER}"|${PROVIDER})\\]`, 'm').test(original)) throw new Error('config.toml already defines an opencode-bridge provider. Remove it before connecting.');
  const lines = original.split('\n');
  const firstTable = lines.findIndex(line => /^\s*\[/.test(line));
  const rootEnd = firstTable < 0 ? lines.length : firstTable;
  const removed: string[] = [];
  const kept = lines.filter((line, index) => {
    if (index >= rootEnd || !new RegExp(`^\\s*(${ROOT_KEYS.join('|')})\\s*=`).test(line)) return true;
    removed.push(line); return false;
  });
  const body = kept.join('\n').replace(/\s+$/, '');
  return { text: `${BEGIN}\n${block.join('\n')}\n${END}\n\n${body}${body ? '\n\n' : ''}${BEGIN}\n${table}\n${END}\n`, removed };
}
export function restoreRoot(current: string, removed: string[]): string {
  const pattern = new RegExp(`${escape(BEGIN)}\\n[\\s\\S]*?${escape(END)}\\n?`, 'g');
  const stripped = current.replace(pattern, '').replace(/^\n+/, '').replace(/\n{3,}/g, '\n\n').replace(/\s+$/, '');
  const prefix = removed.length ? `${removed.join('\n')}\n` : '';
  const text = `${prefix}${prefix && stripped ? '\n' : ''}${stripped}`;
  return text ? `${text}\n` : '';
}
const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export interface CodexLifecycle {
  cli(): Promise<boolean>;
  app(): Promise<string | undefined>;
  running(): Promise<boolean>;
  quit(): Promise<void>;
  open(): Promise<void>;
  terminal(command: string): Promise<void>;
}
// The UI polls status every few seconds; remember a found bundle instead of re-running defaults(1).
let foundApp: string | undefined;
async function findApp(): Promise<string | undefined> {
  if (foundApp) { try { await access(foundApp); return foundApp; } catch { foundApp = undefined; } }
  for (const path of ['/Applications/Codex.app', '/Applications/ChatGPT.app', join(homedir(), 'Applications', 'Codex.app'), join(homedir(), 'Applications', 'ChatGPT.app')]) {
    try { const { stdout } = await exec('/usr/bin/defaults', ['read', join(path, 'Contents', 'Info'), 'CFBundleIdentifier']); if (stdout.trim() === 'com.openai.codex') return foundApp = path; } catch {}
  }
  return undefined;
}
export const codexLifecycle: CodexLifecycle = {
  async cli() {
    const dirs = (process.env.PATH || '').split(delimiter).concat(join(homedir(), '.local', 'bin'), '/opt/homebrew/bin', '/usr/local/bin');
    for (const dir of dirs) { try { await access(join(dir, 'codex')); return true; } catch {} }
    return false;
  },
  app: findApp,
  async running() {
    if (process.platform !== 'darwin') return false;
    try { const { stdout } = await exec('/usr/bin/osascript', ['-e', 'application id "com.openai.codex" is running']); return stdout.trim() === 'true'; } catch { return false; }
  },
  async quit() {
    await exec('/usr/bin/osascript', ['-e', 'tell application id "com.openai.codex" to quit']);
    const deadline = Date.now() + 15_000;
    while (Date.now() < deadline) { if (!await codexLifecycle.running()) return; await delay(200); }
    throw new Error('The Codex app did not quit. Quit it manually and try again.');
  },
  async open() { await exec('/usr/bin/open', ['-b', 'com.openai.codex']); },
  async terminal(command) {
    await exec('/usr/bin/osascript', ['-e', `tell application "Terminal" to do script ${JSON.stringify(command)}`, '-e', 'tell application "Terminal" to activate']);
  },
};

export class CodexClient implements DesktopClient {
  descriptor = { id: 'codex', name: 'Codex', description: 'Codex CLI & app', availability: 'available' as const, protocol: 'openai-responses' as const };
  constructor(private directory = stateDir(), private home = codexHome(), private lifecycle: CodexLifecycle = codexLifecycle) {}
  private get paths() {
    return { profile: join(this.home, `${CODEX_PROFILE}.config.toml`), catalog: join(this.home, `${CODEX_PROFILE}-models.json`), root: join(this.home, 'config.toml'), journal: join(this.directory, 'codex-journal.json') };
  }
  private route(config: BridgeConfig): Route {
    const route = config.codexRoutes?.[0];
    if (!route) throw new Error('Choose a model for Codex first.');
    return route;
  }
  async inspect(config?: BridgeConfig): Promise<ClientStatus> {
    const [cli, app] = await Promise.all([this.lifecycle.cli(), this.lifecycle.app()]);
    const journal = await readJSON(this.paths.journal);
    const root = await readText(this.paths.root) || '';
    const appConnected = !!journal && root.includes(BEGIN);
    let profileReady = false;
    if (config?.codexRoutes?.length) profileReady = await readText(this.paths.profile) === profileText(config, this.route(config), this.paths.catalog);
    const running = app ? await this.lifecycle.running() : false;
    return { installed: cli || !!app, running, connected: profileReady || appConnected, recoveryNeeded: !!journal && !appConnected, targets: { cli, app: !!app }, appConnected };
  }
  async preview(config: BridgeConfig): Promise<Wire> {
    const route = this.route(config);
    return { profile: this.paths.profile, catalog: this.paths.catalog, appConfig: this.paths.root, model: route.id, backend: route.ref, baseURL: `http://127.0.0.1:${config.port}/v1`, command: `codex --profile ${CODEX_PROFILE}` };
  }
  private async writeProfile(config: BridgeConfig): Promise<void> {
    const route = this.route(config);
    await atomicJSON(this.paths.catalog, catalog(config.codexRoutes!));
    await writePrivate(this.paths.profile, profileText(config, route, this.paths.catalog));
  }
  async launch(config: BridgeConfig, restart: boolean, options: LaunchOptions = {}): Promise<void> {
    const target = options.target || 'cli';
    const status = await this.inspect(config);
    if (target === 'cli' && !status.targets?.cli) throw new Error('Codex CLI was not found. Install it with: npm install -g @openai/codex');
    if (target === 'app' && !status.targets?.app) throw new Error('The Codex app is not installed in Applications.');
    await this.writeProfile(config);
    if (target === 'cli') { await this.lifecycle.terminal(`codex --profile ${CODEX_PROFILE}`); return; }
    await this.connectApp(config, restart);
  }
  async apply(config: BridgeConfig, restart: boolean, prepare: () => Promise<void>): Promise<void> {
    const appConnected = !!await readJSON(this.paths.journal);
    await prepare();
    await this.writeProfile(config);
    if (appConnected) { await this.restoreApp(false); await this.connectApp(config, restart); }
  }
  private async connectApp(config: BridgeConfig, restart: boolean): Promise<void> {
    const reopen = await this.lifecycle.running();
    if (reopen && !restart) throw new Error('The Codex app is running. Quit it first or enable “Restart if needed”.');
    await withLock(this.directory, async () => {
      if (await readJSON(this.paths.journal)) return;
      const original = await readText(this.paths.root);
      const route = this.route(config);
      const { text, removed } = applyRoot(original || '', selection(route, this.paths.catalog), providerTable(config));
      // Journal first, so an interruption can always be restored.
      await atomicJSON(this.paths.journal, { version: 1, removed, created: original === undefined });
      await writePrivate(this.paths.root, text);
    });
    if (reopen) await this.lifecycle.quit();
    await this.lifecycle.open();
  }
  private async restoreApp(restart: boolean): Promise<boolean> {
    return withLock(this.directory, async () => {
      const journal = await readJSON(this.paths.journal);
      if (!journal) return false;
      if (journal.version !== 1 || !Array.isArray(journal.removed)) throw new Error('Invalid Codex recovery journal.');
      const reopen = restart && await this.lifecycle.running();
      if (reopen) await this.lifecycle.quit();
      const current = await readText(this.paths.root);
      if (current !== undefined) {
        const restored = restoreRoot(current, journal.removed);
        if (!restored && journal.created) await unlink(this.paths.root).catch(() => {});
        else await writePrivate(this.paths.root, restored);
      }
      await unlink(this.paths.journal);
      if (reopen) await this.lifecycle.open();
      return true;
    });
  }
  async disconnect(restart: boolean): Promise<boolean> {
    const restored = await this.restoreApp(restart);
    let removed = false;
    for (const path of [this.paths.profile, this.paths.catalog]) {
      try { await unlink(path); removed = true; } catch (err: any) { if (err.code !== 'ENOENT') throw err; }
    }
    return restored || removed;
  }
}
